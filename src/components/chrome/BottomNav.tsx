export default function BottomNav() {
  const pathname = usePathname();
  const { address } = useAccount();

  // Get the correct profile href based on whether user is connected
  const getHref = (item: NavItem) => {
    if (item.href === '/profile' && address) {
      return `/profile/${address}`;
    }
    return item.href;
  };

  // Check if current path matches nav item
  const isActive = (item: NavItem) => {
    if (item.href === '/') {
      return pathname === '/';
    }
    if (item.href === '/profile') {
      return pathname.startsWith('/profile');
    }
    return pathname.startsWith(item.href);
  };

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-white/5 bg-[#050507]/95 backdrop-blur-xl md:hidden">
      <div className="mx-auto flex max-w-lg items-center justify-around px-2 py-2">
        {navItems.map((item) => {
          const active = isActive(item);
          const href = getHref(item);

          return (
            <Link
              key={item.href}
              href={href}
              className={`flex min-h-[44px] min-w-[44px] flex-col items-center justify-center gap-1 rounded-xl px-3 py-2 transition-colors ${
                active
                  ? 'text-base-blue'
                  : 'text-white/40 hover:text-white/60'
              }`}
            >
              {active ? item.activeIcon : item.icon}
              <span className="text-[10px] font-medium">{item.label}</span>
            </Link>
          );
        })}
      </div>
      
      {/* Safe area for iOS devices */}
      <div className="h-safe-area-inset-bottom bg-[#050507]" />
    </nav>
  );
}







